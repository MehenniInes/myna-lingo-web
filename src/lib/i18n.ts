// ---------- Date/time locale helpers ----------

const LOCALE_TAG: Record<Locale, string> = {
  en: "en-GB",
  fr: "fr-FR",
  ar: "ar-DZ",
};

export function formatDateTime(locale: Locale, iso: string): string {
  try {
    return new Date(iso).toLocaleString(LOCALE_TAG[locale], {
      weekday: "short",
      day: "2-digit",
      month: "short",
      year: "numeric",
      hour: "2-digit",
      minute: "2-digit",
    });
  } catch {
    return iso;
  }
}

export function formatShortDateTime(locale: Locale, iso: string): string {
  try {
    return new Date(iso).toLocaleString(LOCALE_TAG[locale], {
      day: "2-digit",
      month: "short",
      year: "numeric",
      hour: "2-digit",
      minute: "2-digit",
    });
  } catch {
    return iso;
  }
}

export function timeAgoShort(locale: Locale, iso: string): string {
  const diff = Date.now() - new Date(iso).getTime();
  const mins = Math.floor(diff / 60000);
  if (mins < 1) {
    return locale === "ar" ? "الآن" : locale === "fr" ? "à l'instant" : "just now";
  }
  if (mins < 60) {
    return locale === "ar"
      ? `قبل ${mins} د`
      : locale === "fr"
      ? `il y a ${mins} min`
      : `${mins}m ago`;
  }
  const hours = Math.floor(mins / 60);
  if (hours < 24) {
    return locale === "ar"
      ? `قبل ${hours} س`
      : locale === "fr"
      ? `il y a ${hours} h`
      : `${hours}h ago`;
  }
  const days = Math.floor(hours / 24);
  return locale === "ar"
    ? `قبل ${days} ي`
    : locale === "fr"
    ? `il y a ${days} j`
    : `${days}d ago`;
}

export type TranslationKey = keyof typeof translations.en;

export function t(
  locale: Locale,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const dict = translations[locale] ?? translations.en;
  let str: string = (dict as any)[key] ?? (translations.en as any)[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return str;
}